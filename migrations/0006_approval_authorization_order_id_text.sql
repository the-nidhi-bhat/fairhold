-- FairHold migration 0006: approval, authorization, and order ID columns to text.
--
-- The application uses string IDs that are not always valid UUIDs (for example,
-- approval IDs such as "approval-5fb17238-..." and authorization/order IDs such
-- as "<deal-id>-authorization"). The milestone_approvals, payment_authorizations,
-- and payment_orders tables declared these primary key columns as uuid, which
-- rejected non-UUID string IDs during import.
--
-- These columns are never referenced as foreign-key targets by any other table:
--   - milestone_approvals.id is read/written directly, never an FK target
--   - payment_authorizations.id is not an FK target; payment_captures references
--     payment_authorizations.provider_reference instead
--   - payment_orders.id is not an FK target
--
-- Changing them to text preserves all existing application string IDs while
-- continuing to accept UUIDs generated by randomUUID() for new records.
ALTER TABLE milestone_approvals ALTER COLUMN id TYPE text USING id::text;
ALTER TABLE payment_authorizations ALTER COLUMN id TYPE text USING id::text;
ALTER TABLE payment_orders ALTER COLUMN id TYPE text USING id::text;
